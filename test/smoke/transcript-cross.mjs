const diff=(a,b,path='$')=>{
  if(isDeepStrictEqual(a,b))return []
  if(Array.isArray(a)&&Array.isArray(b)){
    const out=[];for(let i=0;i<Math.max(a.length,b.length);i++)out.push(...diff(a[i],b[i],`${path}[${i}]`));return out
  }
  if(isObj(a)&&isObj(b)){
    const out=[];for(const key of new Set([...Object.keys(a),...Object.keys(b)]))out.push(...diff(a[key],b[key],`${path}.${key}`));return out
  }
  return [`${path}: expected ${JSON.stringify(a)} got ${JSON.stringify(b)}`]
}

