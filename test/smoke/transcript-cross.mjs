const pairs=[['claude','codex'],['codex','claude']]
const matrix={},failures=[],warnings={}
const only=process.env.CROSS_PAIR?.split('->')
for(const [src,dst] of pairs){
  if(only&&(only[0]!==src||only[1]!==dst))continue
  const name=`${src}->${dst}`
  try{
    const d=await runPair(src,dst)
    if(d.native.warnings.length)warnings[name]=d.native.warnings
    matrix[name]=d.diff.length===0&&d.native.errors.length===0?'pass':'fail'
    if(d.diff.length)failures.push({pair:name,failure:'normalize(U2) != degrade(normalize(U1))',diff:d.diff,expected:degrade(dst,d.n1),actual:d.n2})
    if(d.native.errors.length)failures.push({pair:name,failure:'native whitelist lint',file:d.native.file,errors:d.native.errors})
    if(process.env.CROSS_TRACE===name)console.error(JSON.stringify({trace:name,lawfulLoss:d.degraded},null,2))
  }catch(error){
    matrix[name]='fail'
    failures.push({pair:name,failure:String(error.message??error)})
  }
}

if(failures.length){
  console.error(JSON.stringify({passed:false,matrix,failures,warnings,home,cli:log},null,2))
  process.exit(1)
}
