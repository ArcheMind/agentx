// normalize: strip everything an importer legitimately regenerates; what remains is pure semantics.
// ---------------------------------------------------------------------------------------------
// Session envelope (id/source/title/counts/times/workspace), message id/parentId and timestamps are regenerated by every
// import; tool ids are renamed to first-appearance tokens so only the tool_use -> tool linkage structure is compared.
function normalize(unified){
  const tokens=new Map()
  const token=id=>{if(!tokens.has(id))tokens.set(id,'T'+(tokens.size+1));return tokens.get(id)}
  return unified.messages.map(m=>{
    const out={role:m.role}
    if(m.content!==undefined)out.content=m.content.map(b=>b.type==='tool_use'?{...b,id:token(b.id)}:b)
    if(m.model!==undefined)out.model=m.model
    if(m.stopReason!==undefined)out.stopReason=m.stopReason
    if(m.role==='tool'){
      out.toolUseId=token(m.toolUseId)
      out.toolName=m.toolName
      // Spec: isError is optional and "true when the tool execution failed", so absent and false are the same fact.
      out.isError=m.isError===true
      if(m.result!==undefined)out.result=m.result
    }
    return out
  })
}

// ---------------------------------------------------------------------------------------------
// degrade: the lawful loss of each destination, derived from the unified spec
// (agentx-protocol docs/unified-transcript-format.md, v0.2.0) and the native formats in docs/native-rollout-protocols/.
// Written independently of the serializers; every rule cites its justification. "spec gap:" marks a rule the spec does not state.
// ---------------------------------------------------------------------------------------------
const isImage=b=>b.type==='image'
// spec gap: the spec defines no block-array -> text projection; text blocks joined by "\n" is the line-oriented reading of tool output.
const textProjection=result=>typeof result==='string'?result:Array.isArray(result)?result.filter(b=>b&&typeof b.text==='string').map(b=>b.text).join('\n'):JSON.stringify(result)

// spec gap: the Codex table says only function_call/custom_tool_call are appended to the *preceding* assistant message; a reasoning item is a standalone
// response_item, so a thinking run followed by a text block (a separate codex message item) comes back as its own assistant message.
function splitReasoning(m){
  if(m.role!=='assistant')return [m]
  const at=m.content.findIndex((b,i)=>b.type==='text'&&i>0&&m.content[i-1].type==='thinking')
  return at<0?[m]:[{...m,content:m.content.slice(0,at)},{...m,content:m.content.slice(at)}]
}

function degrade(dst,messages){
  let list=structuredClone(messages)
  // spec gap: pi has no system role (native roles are user/assistant/toolResult, pi PROTOCOL) and the spec maps no unified system message into pi; system messages are dropped.
  if(dst==='pi')list=list.filter(m=>m.role!=='system')
  if(dst==='codex')list=list.flatMap(splitReasoning)
  return list.map(m=>{
    if(dst==='codex'||dst==='pi'){
      // spec gap: the spec maps no unified image block into codex (input_text only) or pi (user content is text blocks only); image is dropped.
      if(m.content)m.content=m.content.filter(b=>!isImage(b))
    }
    if(dst==='codex'){
      // Codex table in the spec maps no model/stopReason; a codex message item has neither field (codex PROTOCOL ContentItem/message).
      delete m.model
      delete m.stopReason
      if(m.role==='tool'){
        // Spec Codex table: function_call_output `output` -> string `result`; codex rollout has no error flag on function_call_output (codex PROTOCOL), so isError is lost.
        m.isError=false
        // Spec Codex table: tool output is a string result, so a foreign structured result is stored as its text projection.
        m.result=textProjection(m.result)
      }
    }
    if(dst==='pi'&&m.role==='tool'){
      // Pi PROTOCOL: toolResult `content` MUST be a non-null array of text/image blocks; spec Pi table: content block array -> `result` verbatim, so a string result comes back as one text block.
      // spec gap: a result that is not a pi block array (foreign block types such as codex input_text) has no stated mapping; it is stored as one text block holding its text projection.
      const piShaped=Array.isArray(m.result)&&m.result.every(b=>b&&(b.type==='text'||b.type==='image'))
      if(!piShaped)m.result=[{type:'text',text:textProjection(m.result)}]
    }
    // Claude: spec Claude table reverses every row (result -> tool_result.content, image -> image, system -> system record, model/stop_reason, thinking signature), so nothing is lost.
    return m
  })
}

