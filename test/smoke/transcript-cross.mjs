async function runPair(src,dst){
  const detail={}
  const u1Text=ax('--json','session','export',providers[src].id,'--source',src)
  const u1=JSON.parse(u1Text)
  const u1File=join(home,`${src}-to-${dst}-u1.json`)
  await writeFile(u1File,u1Text)
  const imported=JSON.parse(ax('--json','session','import',dst,u1File))
  if(imported.agent!==dst)throw new Error('import agent '+JSON.stringify(imported))
  let written,id
  if(dst==='pi'){
    // Pi import writes a resume file for `pi --session`, not into pi's session store; place it where pi's store scan finds it so export can read it back.
    written=imported.session
    id=basename(written,'.jsonl')
    await mkdir(dirname(join(home,providers.pi.path(id))),{recursive:true})
    await copyFile(written,join(home,providers.pi.path(id)))
  }else{
    id=imported.session
    written=await findFile(join(home,dst==='claude'?'.claude/projects':'.codex/sessions'),id+'.jsonl')
  }
  if(!written?.startsWith(home+'/'))throw new Error('import did not land inside isolated HOME: '+written)
  const u2=JSON.parse(ax('--json','session','export',id,'--source',dst))
  const warnings=[]
  detail.native={file:written,errors:lint[dst](await jsonl(written),written,warnings),warnings}
  const n1=normalize(u1),n2=normalize(u2),expected=degrade(dst,n1)
  detail.diff=diff(expected,n2)
  detail.degraded=diff(n1,expected)
  detail.n1=n1;detail.n2=n2
  return detail
}

